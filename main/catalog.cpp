const std::array<ShapePreset, kShapeCount> &shapes() { return kShapes; }
const std::array<Palette, kPaletteCount> &palettes() { return kPalettes; }

const ShapePreset &shape_at(int index)
{
    return kShapes[static_cast<std::size_t>(wrap_index(index, static_cast<int>(kShapeCount)))];
}

const Palette &palette_at(int index)
{
    return kPalettes[static_cast<std::size_t>(wrap_index(index, static_cast<int>(kPaletteCount)))];
}

Selection wrap_selection(Selection selection)
{
    selection.shape = wrap_index(selection.shape, static_cast<int>(kShapeCount));
    selection.palette = wrap_index(selection.palette, static_cast<int>(kPaletteCount));
    return selection;
}

Selection offset_selection(Selection selection, int delta_shape, int delta_palette)
{
    selection.shape += delta_shape;
    selection.palette += delta_palette;
    return wrap_selection(selection);
}

